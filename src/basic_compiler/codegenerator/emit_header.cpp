#include "basic_compiler/codegen/CodeGenerator.h"
#include <sstream>

namespace gwbasic {

void CodeGenerator::emitHeader(std::ostringstream& out) {
    /*
     * Function: CodeGenerator::emitHeader
     * Inputs:
     *  - out: IR output stream to append to
     * Outputs:
     *  - void
     * Theory of operation:
     *  - Writes a generation banner and external declarations (printf/scanf)
     *    needed by the emitted IR.
     */
    out << ";; Generated by gwbasic::CodeGenerator" << STR_LF << STR_LF
        << "declare i32 @printf(ptr, ...)" << STR_LF
        << "declare i32 @scanf(ptr, ...)" << STR_LF
        << "declare i32 @strcmp(ptr, ptr)" << STR_LF
        << "declare i64 @strlen(ptr)" << STR_LF
        << "declare ptr @malloc(i64)" << STR_LF
        << "declare ptr @strcpy(ptr, ptr)" << STR_LF
        << "declare ptr @strcat(ptr, ptr)" << STR_LF << STR_LF
        << "declare ptr @strncpy(ptr, ptr, i64)" << STR_LF
    // File I/O
        << "declare ptr @fopen(ptr, ptr)" << STR_LF
        << "declare i32 @fclose(ptr)" << STR_LF
        << "declare i32 @fprintf(ptr, ptr, ...)" << STR_LF
        << "declare i64 @fread(ptr, i64, i64, ptr)" << STR_LF
        << "declare i64 @fwrite(ptr, i64, i64, ptr)" << STR_LF << STR_LF
        << "declare i32 @chdir(ptr)" << STR_LF
        << "declare double @atof(ptr)" << STR_LF << STR_LF
    // Math library functions used by intrinsic calls
        << "declare double @sqrt(double)" << STR_LF
        << "declare double @fabs(double)" << STR_LF
        << "declare double @sin(double)" << STR_LF
        << "declare double @cos(double)" << STR_LF
        << "declare double @tan(double)" << STR_LF
        << "declare double @atan(double)" << STR_LF
        << "declare double @log(double)" << STR_LF
        << "declare double @exp(double)" << STR_LF
        << "declare double @floor(double)" << STR_LF << STR_LF
    // Additional helpers for extended math/CVT
        << "declare double @drand48()" << STR_LF
        << "declare double @round(double)" << STR_LF << STR_LF
    // RNG seed + time
        << "declare void @srand48(i64)" << STR_LF
        << "declare i64 @time(ptr)" << STR_LF << STR_LF;

    // Provide helper implementing full RND(x) semantics if needed
    if (needsRndHelper_) {
        out << "define double @gwb_rnd(double %x) {" << STR_LF
            << "entry:" << STR_LF
            << "  %iszero = fcmp oeq double %x, 0.0" << STR_LF
            << "  br i1 %iszero, label %retlast, label %nonzero" << STR_LF
            << "retlast:" << STR_LF
            << "  %last = load double, ptr @gwb_last_rnd" << STR_LF
            << "  ret double %last" << STR_LF
            << "nonzero:" << STR_LF
            << "  %isneg = fcmp olt double %x, 0.0" << STR_LF
            << "  br i1 %isneg, label %seedcase, label %gen" << STR_LF
            << "seedcase:" << STR_LF
            << "  %xi = fptosi double %x to i64" << STR_LF
            << "  call void @srand48(i64 %xi)" << STR_LF
            << "  br label %gen" << STR_LF
            << "gen:" << STR_LF
            << "  %rv = call double @drand48()" << STR_LF
            << "  store double %rv, ptr @gwb_last_rnd" << STR_LF
            << "  ret double %rv" << STR_LF
            << "}" << STR_LF << STR_LF;
    }
    // Provide a minimal CALL helper that interprets the first byte at the
    // effective address as an opcode. Currently, opcode 1 prints "CALLED\n".
    out << "define void @gwb_call(i64 %addr) {" << STR_LF
        << "entry:" << STR_LF
        << "  %p = getelementptr inbounds [1048576 x i8], ptr @gwb_mem, i64 0, i64 %addr" << STR_LF
        << "  %op = load i8, ptr %p" << STR_LF
        << "  %is1 = icmp eq i8 %op, 1" << STR_LF
        << "  br i1 %is1, label %case1, label %ret" << STR_LF
        << "case1:" << STR_LF
        << "  %fmt = getelementptr inbounds i8, ptr @.call_msg, i64 0" << STR_LF
        << "  call i32 (ptr, ...) @printf(ptr %fmt)" << STR_LF
        << "  br label %ret" << STR_LF
        << "ret:" << STR_LF
        << "  ret void" << STR_LF
        << "}" << STR_LF << STR_LF;
    // Global table for file channels (1..16)
    out << "@gwb_files = internal global [16 x ptr] zeroinitializer" << STR_LF << STR_LF;
    log() << "emitHeader: declared stdio + globals" << CH_LF;
}

} // namespace gwbasic
